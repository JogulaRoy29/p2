class AddNumbers {
    public static void main(String args[]) {
        int a = 10;
        int b = 20;

        System.out.println("Input:");
        System.out.println("a = " + a);
        System.out.println("b = " + b);

        int sum = a + b;

        System.out.println("Output:");
        System.out.println("Sum = " + sum);
    }
}
